from . import put

LETTERS = "ABCDEFGHIJKL"


def _where(n):
    """Где искать катушку с этим номером и чем она отличается от соседних."""
    base = ("Катушка %s обслуживает цилиндр %d: на моторах с индивидуальными катушками она стоит прямо на свече "
            "этого цилиндра, на моторах с модулем зажигания на два цилиндра — это выход модуля, идущий к цилиндру %d."
            % (LETTERS[n - 1], n, n))
    if n == 1:
        return base + " Первый цилиндр считают от привода ГРМ (ремня или цепи), на поперечных моторах это обычно правый по ходу край."
    if n <= 4:
        return base + " Нумерация идёт от привода ГРМ, на V-образных моторах порядок цилиндров смотрят по схеме конкретного мотора."
    if n <= 6:
        return base + " Цилиндры 5 и 6 есть только на 5- и 6-цилиндровых моторах; на V6 это второй ряд (банк 2), порядок — по схеме мотора."
    if n <= 8:
        return base + " Цилиндры 7 и 8 есть только на V8; какой ряд считается первым — смотрят по схеме конкретного мотора."
    return base + (" Цилиндр %d есть только на 10- и 12-цилиндровых моторах; какой ряд и какая катушка — строго по схеме "
                   "этого мотора, на таких машинах катушки часто спрятаны под декоративной крышкой." % n)


