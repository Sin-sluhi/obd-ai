def _pedal_learn(sens, code):
    """Узел «датчик положения педали тормоза: адаптация не выполнена»: цена 1500, s=medium, stop=False."""
    where = ("A — первый из двух датчиков хода педали: блок сравнивает их между собой, поэтому обучаются оба"
             if sens == "A" else
             "B — второй, дублирующий датчик хода педали: без него блок не может проверить первый")
    e = ("%s — адаптация датчика положения педали тормоза %s не выполнена. " % (code, sens) + _BOOSTER +
         "Положение педали блок узнаёт по двум датчикам хода, и для каждого он должен запомнить «ноль» — отпущенную "
         "педаль — и крайнее положение. Код ставится, когда таких значений в памяти нет: блок новый или перепрошит, "
         "усилитель снимали, меняли датчик, педальный узел или надолго обесточивали машину. Датчик %s. Без обучения блок "
         "не знает, сколько вы нажали, и либо помогает с запасом, либо отключает помощь вовсе." % where)
    sy = ["после ремонта тормозов, замены усилителя или блока горит лампа тормозов и ESP",
          "педаль тугая или помощь приходит рывком, «подхватывает» не сразу",
          "иногда никак: только лампа и код, тормозит почти нормально"]
    c = ["после замены блока или усилителя тормозов не выполнена процедура обучения — проверить историю ремонта, "
         "код появился сразу после работ",
         "датчик положения педали или педальный узел снимали и ставили, точка «ноль» сдвинулась — код после "
         "регулировки педали или замены выключателя стоп-сигналов",
         "долгое обесточивание или замена блока с потерей адаптаций — код вместе с ошибками калибровки других блоков",
         "датчик педали даёт сигнал вне допустимого окна, и обучение не проходит — проверить сигнал датчика в данных "
         "блока при отпущенной и нажатой педали"]
    ck = ["Посмотреть в данных блока усилителя сигнал датчика педали: при отпущенной педали значение должно быть "
          "стабильным и не дрожать, при нажатии — плавно расти без скачков",
          "Сравнить сигналы датчиков A и B при одном и том же нажатии: расхождение должно быть небольшим, "
          "иначе обучение не пройдёт",
          "Убедиться, что педаль возвращается до упора: ход свободен, коврик не подпирает, выключатель стоп-сигналов "
          "срабатывает в первые миллиметры хода",
          "Напряжение аккумулятора во время обучения не ниже 12,5 В — процедура прерывается при просадке"]
    d = ("1) Проверить, что педаль ходит свободно и возвращается до упора, убрать лишний коврик. "
         "2) Выполнить обучение датчиков положения педали сканером (у многих марок — «базовая установка» или "
         "«калибровка педали» в блоке тормозов), при заряженном аккумуляторе. "
         "3) Если обучение не проходит — проверить сигналы датчиков и разъём педального узла. "
         "4) Замена датчика или педального узла — только когда обучение не проходит при исправной проводке.")
    x = ["менять датчик педали, не попробовав обучение сканером",
         "прокачивать тормоза — к обучению датчика это не относится",
         "менять блок усилителя целиком из-за одного необученного датчика"]
    rk = ("Пока датчик не обучен, помощь тормозов может быть ограничена или отключена: педаль тугая, тормозной путь "
          "длиннее. Ехать можно аккуратно до сервиса с большой дистанцией, но тянуть не стоит.")
    return dict(e=e, sy=sy, c=c, ck=ck, d=d, x=x, rk=rk, p=1500, s="medium", stop=False)


