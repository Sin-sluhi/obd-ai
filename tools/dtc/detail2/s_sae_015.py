def _motor_pos_supply(mot, code, kind):
    """Узел «питание датчика положения мотора A/B усилителя тормозов»: цена 2000, s=high, stop=True."""
    where = ("A — основной мотор усилителя: на большинстве машин он один"
             if mot == "A" else
             "B — второй мотор или второй канал управления: встречается на усилителях с дублированием, "
             "где помощь обеспечивают два привода")
    if kind == "open":
        e = ("%s — обрыв цепи питания датчика положения мотора %s усилителя тормозов. " % (code, mot) + _BOOSTER +
             "Датчик положения ротора получает от блока опорное питание, и блок проверяет, что напряжение на этой линии "
             "есть. Код ставится, когда питание до датчика не доходит: провод оборван, контакт выпал из разъёма или "
             "внутренняя линия питания в блоке разомкнута. Мотор %s. " % where + _FALLBACK)
        c = ["окисленный или разошедшийся разъём блока усилителя (влага после мойки, вибрация) — осмотр контактов, "
             "подтяжка, следы зелёного налёта",
             "обрыв провода опорного питания в жгуте усилителя — прозвонка линии между блоком и датчиком при "
             "отсоединённых разъёмах",
             "провал напряжения бортсети при запуске с севшим аккумулятором — блок на мгновение теряет питание датчика "
             "и пишет обрыв; код в истории, помощь вернулась после перезапуска",
             "внутренняя неисправность блока усилителя (линия питания датчика внутри корпуса) — только после проверки "
             "аккумулятора, предохранителя и проводки"]
    elif kind == "low":
        e = ("%s — низкое напряжение питания датчика положения мотора %s усилителя тормозов. " % (code, mot) + _BOOSTER +
             "По стандарту «низкий уровень» значит, что линия опорного питания датчика сидит на массе: провод протёрт "
             "об кузов, в разъёме вода, или сам датчик замкнул питание внутри. Блок не может поднять напряжение до "
             "нормы и считает датчик положения непригодным. Мотор %s. " % where + _FALLBACK)
        c = ["вода в разъёме блока усилителя после мойки моторного отсека или езды по лужам — зелёный налёт на "
             "контактах, капли внутри колодки",
             "провод опорного питания протёрт о кузов или кронштейн — на отсоединённом разъёме линия звонится на массу",
             "глубокая просадка напряжения при запуске (севший аккумулятор, окисленные клеммы) — код остался в истории, "
             "сейчас всё работает",
             "замыкание внутри блока усилителя (датчик или его линия питания) — если замыкание не пропадает при "
             "отсоединённом жгуте"]
    elif kind == "high":
        e = ("%s — высокое напряжение питания датчика положения мотора %s усилителя тормозов. " % (code, mot) + _BOOSTER +
             "По стандарту «высокий уровень» значит, что на линии опорного питания напряжение выше нормы: замыкание на "
             "+12 В в жгуте (перетёртая изоляция рядом с силовым проводом) или обрыв сигнального провода, при котором "
             "подтяжка внутри блока держит линию высоко. Блок видит неправильное питание и не доверяет датчику. "
             "Мотор %s. " % where + _FALLBACK)
        c = ["обрыв или выпавший контакт сигнального провода датчика — подтяжка в блоке держит линию высоко; "
             "прозвонка линии от блока до датчика",
             "замыкание линии питания датчика на +12 В в жгуте усилителя — на отсоединённом разъёме на линии есть "
             "напряжение бортсети",
             "перезаряд бортсети (неисправный регулятор генератора, напряжение выше 15 В) — проверить напряжение на "
             "аккумуляторе при работающем моторе",
             "внутренняя неисправность блока усилителя — после проверки проводки и генератора"]
    else:
        e = ("%s — питание датчика положения мотора %s усилителя тормозов вне диапазона. " % (code, mot) + _BOOSTER +
             "Опорное напряжение на датчике есть, но оно гуляет или не совпадает с тем, что выдаёт блок: плохой контакт "
             "в разъёме, подсевшая масса, помехи от силовых проводов или стареющий стабилизатор внутри блока. "
             "Блок не может точно пересчитать сигнал датчика в положение ротора и перестаёт доверять ему. "
             "Мотор %s. " % where + _FALLBACK)
        c = ["подсевший контакт в разъёме блока усилителя (окисление, ослабший фиксатор) — напряжение питания "
             "датчика плавает при шевелении жгута",
             "плохая масса блока усилителя — падение напряжения на массе под нагрузкой больше 0,3 В",
             "нестабильная бортсеть: слабый аккумулятор, окисленные клеммы, просадки при запуске",
             "внутренняя неисправность стабилизатора питания в блоке усилителя — после проверки массы, разъёмов "
             "и аккумулятора"]
    d = ("1) Проверить и при необходимости зарядить или заменить аккумулятор, зачистить клеммы — после запуска с "
         "просадкой код часто остаётся только в истории. "
         "2) Предохранитель и силовой разъём блока усилителя: осмотреть, почистить, подтянуть контакты. "
         "3) Масса блока усилителя на кузов: открутить, зачистить, затянуть. "
         "4) Прозвонить жгут усилителя на обрыв, замыкание на массу и на +12 В, устранить перетирание. "
         "5) Блок усилителя — последним, после подтверждения исправности питания и проводки; новый блок требует "
         "программирования и прокачки у специалиста по тормозам.")
