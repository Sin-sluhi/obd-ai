def _cd(code, cyl, side, kind):
    side_ru = "впускных" if side == "in" else "выпускных"
    what = "клапана управления %s клапанами при отключении цилиндра %d" % (side_ru, cyl)
    note = _cyl_note(cyl)
    if kind == "circuit":
        e = ("%s — неисправность цепи %s (обрыв). %s %s %s Для водителя: система отключения цилиндров выключена, мотор "
             "работает на всех цилиндрах, а причина почти всегда в разъёме, проводе под впуском или обмотке клапана."
             % (code, what, ROLE_CD, note, _kind_text(kind, "клапана")))
        sy = ["чаще всего никак: только лампа Check Engine",
              "расход на трассе выше обычного — отключение цилиндров не работает",
              "код приходит и уходит, если контакт в разъёме плавает"]
        c = ["разъём клапана в масле или окислен, контакт пропадает — осмотр, пошевелить разъём на работающем моторе",
             "обрыв обмотки клапана — сопротивление бесконечное, тогда как у соседних клапанов оно одинаковое и конечное",
             "перетёртый или перегрызенный провод в жгуте под впускным коллектором — прозвонка линии при снятых разъёмах",
             "замыкание обмотки внутри клапана — сопротивление близко к нулю, блок отключает выход по перегрузке",
             "драйвер в блоке двигателя (редко, после замыкания в жгуте) — только после проверки всего остального"]
    elif kind == "low":
        e = ("%s — низкий уровень сигнала в цепи %s. %s %s %s Для водителя: отключение цилиндров не работает, искать надо "
             "замыкание на массу — разъём с маслом, перетёртый провод под впуском, замкнутая обмотка."
             % (code, what, ROLE_CD, note, _kind_text(kind, "клапана")))
        sy = ["чаще всего никак: только лампа Check Engine",
              "расход на трассе выше обычного",
              "код появляется после мойки двигателя или дождя — вода в разъёме"]
        c = ["масло или вода в разъёме клапана замыкают контакты — разъём мокрый, в масле, с зелёным налётом",
             "провод управления перетёрт и замкнут на массу — на снятом разъёме линия звонится на кузов",
             "обмотка клапана замкнута (витки или на корпус) — сопротивление заметно ниже, чем у соседних клапанов",
             "жгут пережат при прошлом снятии впускного коллектора — осмотреть трассу жгута"]
    else:
        e = ("%s — высокий уровень сигнала в цепи %s. %s %s %s Для водителя: отключение цилиндров не работает, искать надо "
             "обрыв провода, выпавший контакт в разъёме или, реже, замыкание на плюс в жгуте."
             % (code, what, ROLE_CD, note, _kind_text(kind, "клапана")))
        sy = ["чаще всего никак: только лампа Check Engine",
              "расход на трассе выше обычного",
              "код приходит прерывисто, на кочках — контакт в разъёме выпадает"]
        c = ["выпавший или отогнутый контакт в разъёме клапана — разъём на вид цел, но контакт не достаёт до вывода",
             "обрыв провода управления между блоком и клапаном — прозвонка на обрыв при снятых разъёмах",
             "обрыв обмотки клапана — сопротивление бесконечное, у соседних клапанов конечное и одинаковое",
             "замыкание провода управления на +12 В в жгуте — на снятом разъёме на линии напряжение бортсети"]
    return dict(e=e, sy=sy, c=c, ck=CK_CD, d=D_CD, x=X_CD, rk=RK_CD, p=3500, s="low", stop=False)


