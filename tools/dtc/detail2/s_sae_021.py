def _kind_text(kind, what):
    """Что именно говорит тип отказа по стандарту (what — «клапана»)."""
    if kind == "circuit":
        return ("Код «цепь» — электрический: блок двигателя, подавая ток на обмотку %s, не видит нормальной нагрузки "
                "(обрыв) или видит замыкание. Сам блок при этом перестаёт управлять узлом и держит его в исходном "
                "положении." % what)
    if kind == "low":
        return ("«Низкий уровень» по стандарту означает, что линия управления сидит на массе: провод замкнут на кузов "
                "или обмотка %s замкнута, либо цепь оборвана и блок видит на выходе ноль. Блок перестаёт управлять узлом "
                "и держит его в исходном положении." % what)
    if kind == "high":
        return ("«Высокий уровень» по стандарту означает замыкание линии управления на питание или обрыв сигнального "
                "провода, при котором на выходе блока остаётся напряжение бортсети, хотя блок пытается его опустить. "
                "Обмотка %s при этом током не управляется, узел стоит в исходном положении." % what)
    return ""


ROLE_CD = ("Система отключения цилиндров (у GM — AFM/DFM, у Chrysler — MDS, у Honda — VCM) на частичной нагрузке "
           "выключает часть цилиндров: электромагнитный клапан по команде блока двигателя подаёт масло в толкатели или "
           "коромысла этого цилиндра, и его клапаны перестают открываться. На каждый отключаемый цилиндр есть свой клапан "
           "(или по одному на впуск и выпуск). Клапаны обычно собраны в масляном блоке под впускным коллектором или в "
           "блоке цилиндров, разъёмы к ним идут одним жгутом под впуском. Нумерация цилиндров — заводская для этого мотора.")


def _cyl_note(cyl):
    """Где этот цилиндр бывает: коды по стандарту заведены на 12 цилиндров, но на обычных машинах их меньше."""
    if cyl <= 4:
        return ("Цилиндр %d есть на любом четырёх-, шести- и восьмицилиндровом моторе; какой именно из них отключается "
                "и где он стоит — по заводской нумерации этого двигателя." % cyl)
    if cyl <= 6:
        return ("Цилиндр %d бывает только на моторах от шести цилиндров (V6, V8 и больше); где он стоит — по заводской "
                "нумерации этого двигателя." % cyl)
    if cyl <= 8:
        return ("Цилиндр %d бывает только на моторах от восьми цилиндров (V8 и больше); где он стоит — по заводской "
                "нумерации этого двигателя." % cyl)
    return ("Цилиндр %d бывает только на моторах с десятью или двенадцатью цилиндрами — на обычных машинах такой код "
            "встречаться не должен; если он пришёл на моторе с меньшим числом цилиндров, это ошибка чтения или прошивки "
            "блока, а не поломка." % cyl)


