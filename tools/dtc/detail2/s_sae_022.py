def _deact_cyl(code, cyl, valves):
    v_txt = "впускных" if valves == "in" else "выпускных"
    other = "P%d" % (int(code[1:]) + (4 if valves == "in" else -4))
    e = ("%s — управление %s клапанами при отключении цилиндра %d не отрабатывает: блок подал команду отключить цилиндр "
         "(или включить обратно), а %s клапаны этого цилиндра не перешли в нужное положение. Номер цилиндра — по заводской "
         "схеме мотора: на V-образных блоках он считается по-разному у разных марок, поэтому сверяться нужно с руководством. "
         "Переключением управляет масло через электромагнитный клапан и переключаемые толкатели, и код «не отрабатывает» "
         "означает не электрику (обрыв и замыкание цепи клапана — соседние коды), а то, что команда ушла, а механика её не "
         "выполнила: давление не поднялось, толкатель не переключился. Если вместе с этим есть %s — не работает весь "
         "цилиндр, а не одна пара клапанов. Для машины это значит, что отключение цилиндров заблокировано и мотор работает "
         "на всех цилиндрах." % (code, v_txt, cyl, v_txt, other))
    sy = ["чаще никак: только лампа и чуть выше расход на трассе",
          "подёргивание в момент переключения режима при спокойной езде",
          "пропуски и стук именно в цилиндре %d, если толкатель заклинил" % cyl,
          "грубый холостой, если клапаны цилиндра не вернулись в рабочий режим"]
    c = list(_DEACT_C)
    c[2] = ("залип электромагнитный клапан отключения цилиндра %d: плунжер не ходит или не возвращается — проверить ход, "
            "подав 12 В на снятый клапан; сопротивление обмотки сравнить с соседними клапанами" % cyl)
    c[3] = ("заклинил или разрушился переключаемый толкатель %s клапана цилиндра %d — подтверждает стук из-под клапанной "
            "крышки и пропуски в этом же цилиндре (P03%02d и общий P0300)" % (v_txt[:-2] + "ого", cyl, cyl))
    ck = list(_DEACT_CK)
    ck[3] = ("Счётчики пропусков по цилиндрам (режим 06): если пропуски именно в цилиндре %d — толкатель или кулачок, "
             "а не клапан управления" % cyl)
    ck[4] = ("Снять клапанную крышку: нажать на толкатели %s клапанов цилиндра %d — ход как у соседних цилиндров; "
             "заедание или «пустой» ход говорит о заклинившем толкателе" % (v_txt, cyl))
    return dict(e=e, sy=sy, c=c, ck=ck, d=_DEACT_D, x=_DEACT_X, rk=_DEACT_RK, p=3500, s="medium", stop=False)


