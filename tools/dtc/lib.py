def hexcode(base, i=0):
    """base — десятичное число (136 → P0136, нумерация SAE десятичная) или строка вида "P0A00"
    для буквенно-цифровых диапазонов (тогда считаем в hex)."""
    if isinstance(base, int):
        return "P%04d" % (base + i)
    return "%s%04X" % (base[0], int(base[1:], 16) + i)


def block(base, name, fam, kind, nums=(0, 1, 2, 3, 4), m1=None, causes1=None, e=None, s=None, titles=None):
    """Стандартная пятёрка. titles — переопределить названия хвостов."""
    spec = KIND[kind]
    for i in nums:
        suffix, meaning, causes = spec[i]
        if titles and i in titles: suffix = titles[i]
        c = hexcode(base, i)
        if i == 1:
            code(c, "%s: %s" % (name, suffix), fam, m=m1 or meaning, causes=causes1, e=e, s=s)
        else:
            code(c, "%s: %s" % (name, suffix), fam, m=meaning, causes=causes, e=e, s=s)

