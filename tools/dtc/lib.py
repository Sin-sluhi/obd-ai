"""Помощники для описания кодов.

code(...)  — один код руками.
block(...) — стандартная пятёрка SAE «цепь / вне диапазона / низкий / высокий / прерывистый»
             для датчика или исполнительного механизма с учётом его физики (kind).
"""
from families import F

CODES = {}


def code(c, t, f, m="", e="", causes=None, s=None, d=None, r=None, stop=None, p=None):
    """c код, t короткое название, f семейство, m что именно увидел блок (одна фраза),
    e добавка к рассказу семейства, causes/s/d — переопределение семейства, r — связи с конкретными кодами."""
    assert f in F, (c, f)
    assert c not in CODES, c
    entry = {"t": t, "f": f}
    if m: entry["m"] = m
    if e: entry["e"] = e.strip()
    if causes: entry["c"] = causes
    if s: entry["s"] = s
    if d: entry["d"] = d
    if r: entry["r"] = r
    if stop is not None: entry["stop"] = stop
    if p: entry["p"] = p
    CODES[c] = entry
    return entry


